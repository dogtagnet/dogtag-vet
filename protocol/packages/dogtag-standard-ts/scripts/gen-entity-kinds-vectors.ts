// Generate specs/entity-kinds-vectors.json - conformance vectors for the entity kind mask rules
// (specs/entity-kinds.md). Reference implementation: src/entityKinds.ts. The conformance test
// (test/entity_kinds_vectors.test.ts) recomputes every value by hand-written bit logic from
// specs/entity-kinds.json, independently of this generator and of the helper, and the Swift client
// mirrors the same file. Masks are decimal strings because a uint256 does not fit in a JSON number.
import {writeFileSync} from "node:fs";
import {dirname, resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {
  entityKindsFromMask,
  maskFromEntityKinds,
  primaryEntityKind,
  type EntityKindId,
} from "../src/entityKinds.js";

const __dirname = dirname(fileURLToPath(import.meta.url));

const MASKS: {name: string; mask: bigint}[] = [
  {name: "zero mask", mask: 0n},
  {name: "vet only", mask: 2n},
  {name: "government only", mask: 4n},
  {name: "groomer only", mask: 8n},
  {name: "boarding only", mask: 16n},
  {name: "daycare only", mask: 32n},
  {name: "vet and groomer", mask: 10n},
  {name: "vet and daycare", mask: 34n},
  {name: "boarding and daycare", mask: 48n},
  {name: "all five kinds", mask: 62n},
  {name: "bit 0 only is dropped", mask: 1n},
  {name: "bit 0 with vet is dropped", mask: 3n},
  {name: "only bit 6 is unknown", mask: 1n << 6n},
  {name: "only bit 255 is unknown", mask: 1n << 255n},
  {name: "vet with unknown bit 6", mask: 2n | (1n << 6n)},
  {name: "groomer with unknown bit 9, primary is the lowest known bit", mask: 8n | (1n << 9n)},
  {name: "daycare with bit 0 and bit 200", mask: 1n | 32n | (1n << 200n)},
  {name: "every bit of a uint256 set", mask: (1n << 256n) - 1n},
];

const FROM_IDS: {name: string; kinds: string[]}[] = [
  {name: "single vet", kinds: ["VET"]},
  {name: "vet and groomer", kinds: ["VET", "GROOMER"]},
  {name: "order does not matter", kinds: ["GROOMER", "VET"]},
  {name: "all five kinds", kinds: ["DAYCARE", "BOARDING", "GROOMER", "GOVERNMENT", "VET"]},
  {name: "daycare alone", kinds: ["DAYCARE"]},
];

const FROM_IDS_ERRORS: {name: string; kinds: string[]; error: string}[] = [
  {name: "empty list", kinds: [], error: "empty"},
  {name: "unknown id", kinds: ["VET", "KENNEL"], error: "unknown_id"},
  {name: "ids are case sensitive", kinds: ["vet"], error: "unknown_id"},
  {name: "duplicate id", kinds: ["VET", "VET"], error: "duplicate"},
  {name: "duplicate id not adjacent", kinds: ["VET", "GROOMER", "VET"], error: "duplicate"},
];

const out = {
  _comment:
    "WP4.21 entity kind mask vectors (specs/entity-kinds.md). Generated by " +
    "packages/dogtag-standard-ts/scripts/gen-entity-kinds-vectors.ts from src/entityKinds.ts; verified " +
    "independently by test/entity_kinds_vectors.test.ts (hand-written bit logic from specs/entity-kinds.json). " +
    "mask is a decimal uint256 string; kinds are in bit order; primary is the lowest set KNOWN bit or null. " +
    "fromIds gives the mask for a list of ids; fromIdsErrors lists inputs that must be rejected.",
  registryVersion: 1,
  fromMask: MASKS.map(({name, mask}) => ({
    name,
    mask: mask.toString(10),
    kinds: entityKindsFromMask(mask),
    primary: primaryEntityKind(mask),
  })),
  fromIds: FROM_IDS.map(({name, kinds}) => ({
    name,
    kinds,
    mask: maskFromEntityKinds(kinds as EntityKindId[]).toString(10),
  })),
  fromIdsErrors: FROM_IDS_ERRORS.map((v) => {
    let threw = false;
    try {
      maskFromEntityKinds(v.kinds as EntityKindId[]);
    } catch {
      threw = true;
    }
    if (!threw) throw new Error(`generator: expected ${v.name} to be rejected`);
    return v;
  }),
};

const path = resolve(__dirname, "..", "..", "..", "specs", "entity-kinds-vectors.json");
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
console.log(
  `wrote ${path}: ${out.fromMask.length} fromMask, ${out.fromIds.length} fromIds, ${out.fromIdsErrors.length} fromIdsErrors`,
);
